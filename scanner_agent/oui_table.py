"""
scanner_agent/oui_table.py — Offline MAC OUI vendor lookup table.

Extracted from evaluator.py for single-responsibility principle.
Each 3-byte OUI prefix maps to a vendor name.

Usage:
    from scanner_agent.oui_table import resolve_mac_vendor
    vendor = resolve_mac_vendor("00:11:24:ab:cd:ef")  # -> "Apple"

To keep this table current, run:
    python scripts/update_oui.py  (fetches from https://maclookup.app/downloads/json-database)
"""


def resolve_mac_vendor(mac_address: str) -> str:
    """
    Perform an offline OUI lookup for a given MAC address.
    Returns the vendor name string or 'Unknown' if not found.
    """
    if not mac_address:
        return "Unknown"
    mac_clean = mac_address.lower().replace("-", ":").strip()
    # Extract 3-byte OUI prefix (xx:xx:xx)
    parts = mac_clean.split(":")
    if len(parts) < 3:
        return "Unknown"
    prefix = ":".join(parts[:3])
    return _OUI_TABLE.get(prefix, "Unknown")


